/** 长方形（画长方形长宽比用） */
function rect(step, x, y, w, h, color = SOFT_A) {
  return [
    region(
      step,
      [
        { x, y },
        { x: x + w, y },
        { x: x + w, y: y + h },
        { x, y: y + h },
      ],
      { color, opacity: 0.9 },
    ),
    line(
      step,
      [
        { x, y },
        { x: x + w, y },
        { x: x + w, y: y + h },
        { x, y: y + h },
      ],
      { closed: true },
    ),
  ];
}

