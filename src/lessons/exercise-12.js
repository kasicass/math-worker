/** 按比切分的长条：divisions 份里前 shaded 份涂色 */
function bar(step, x, y, width, height, divisions, shaded, color = SOFT_A) {
  const items = [];
  const unit = width / divisions;
  items.push(
    line(
      step,
      [
        { x, y },
        { x: x + width, y },
        { x: x + width, y: y + height },
        { x, y: y + height },
      ],
      { closed: true },
    ),
  );
  if (shaded > 0) {
    items.push(
      region(
        step,
        [
          { x, y },
          { x: x + shaded * unit, y },
          { x: x + shaded * unit, y: y + height },
          { x, y: y + height },
        ],
        { color, opacity: 0.95 },
      ),
    );
  }
  for (let i = 1; i < divisions; i += 1) {
    items.push(
      line(step, [
        { x: x + i * unit, y },
        { x: x + i * unit, y: y + height },
      ], { color: '#ffffff', opacity: 0.9 }),
    );
  }
  return items;
}

