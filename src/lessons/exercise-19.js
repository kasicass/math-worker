/** 两条线段对比（原来 / 现在），标签放在线段外面 */
function compare(step, base, now, labelBase = '原来', labelNow = '现在') {
  const max = Math.max(base, now);
  const unit = 5.2 / max;
  const height = 0.6;
  const left = -2.6;
  const items = [];
  const bars = [
    { value: base, y: 0.7, color: SOFT_A, label: `${labelBase} ${base}`, labelY: 1.55 },
    { value: now, y: -0.5, color: SOFT_B, label: `${labelNow} ${now}`, labelY: -0.95 },
  ];
  for (const bar of bars) {
    items.push(
      region(
        step,
        [
          { x: left, y: bar.y },
          { x: left + bar.value * unit, y: bar.y },
          { x: left + bar.value * unit, y: bar.y + height },
          { x: left, y: bar.y + height },
        ],
        { color: bar.color, opacity: 0.9 },
      ),
      line(
        step,
        [
          { x: left, y: bar.y },
          { x: left + bar.value * unit, y: bar.y },
          { x: left + bar.value * unit, y: bar.y + height },
          { x: left, y: bar.y + height },
        ],
        { closed: true },
      ),
      text(step, left + (bar.value * unit) / 2, bar.labelY, bar.label, { size: 0.3 }),
    );
  }
  return items;
}

